-- Stage 3: internal staff identities and owner-scoped support records.
create type public.staff_role as enum ('staff', 'admin');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  role public.staff_role not null default 'staff',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.support_requests (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  subject text not null check (length(trim(subject)) between 1 and 200),
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index support_requests_owner_id_idx
  on public.support_requests (owner_id);

alter table public.profiles enable row level security;
alter table public.support_requests enable row level security;

-- SECURITY DEFINER avoids recursive profile-policy evaluation. The fixed
-- search_path and explicit schema names prevent object-shadowing attacks.
create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create policy "users read their own profile"
  on public.profiles for select
  to authenticated
  using (id = (select auth.uid()));

create policy "admins read all profiles"
  on public.profiles for select
  to authenticated
  using ((select public.is_admin()));

create policy "users update their own profile"
  on public.profiles for update
  to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "admins update other profiles"
  on public.profiles for update
  to authenticated
  using ((select public.is_admin()) and id <> (select auth.uid()))
  with check (id <> (select auth.uid()));

revoke all on table public.profiles from anon, authenticated;
grant select on table public.profiles to authenticated;
-- Ordinary users may only change this non-security-sensitive column.
grant update (display_name) on table public.profiles to authenticated;

create function public.set_staff_role(
  target_user_id uuid,
  new_role public.staff_role
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'administrator access required' using errcode = '42501';
  end if;

  if target_user_id = auth.uid() then
    raise exception 'administrators cannot change their own role'
      using errcode = '42501';
  end if;

  update public.profiles set role = new_role, updated_at = now()
  where id = target_user_id;

  if not found then
    raise exception 'profile not found' using errcode = 'P0002';
  end if;
end;
$$;

revoke all on function public.set_staff_role(uuid, public.staff_role) from public;
grant execute on function public.set_staff_role(uuid, public.staff_role)
  to authenticated;

create policy "owners create support requests"
  on public.support_requests for insert
  to authenticated
  with check (owner_id = (select auth.uid()));

create policy "owners read support requests"
  on public.support_requests for select
  to authenticated
  using (owner_id = (select auth.uid()) or (select public.is_admin()));

create policy "owners update support requests"
  on public.support_requests for update
  to authenticated
  using (owner_id = (select auth.uid()) or (select public.is_admin()))
  with check (owner_id = (select auth.uid()) or (select public.is_admin()));

create policy "owners delete support requests"
  on public.support_requests for delete
  to authenticated
  using (owner_id = (select auth.uid()) or (select public.is_admin()));

revoke all on table public.support_requests from anon, authenticated;
grant select, insert, update, delete on table public.support_requests
  to authenticated;
grant usage, select on sequence public.support_requests_id_seq to authenticated;

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', new.email));
  return new;
end;
$$;

revoke all on function public.handle_new_user() from public;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
